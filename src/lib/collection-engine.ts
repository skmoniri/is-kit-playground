
import {
  arrayOf,
  nonEmptyArrayOf,
  tupleOf,
  setOf,
  mapOf,
  recordOf,
  safeParse,
  safeJsonParse,
} from "is-kit";

import { guardLookup } from "../data/guards";

import type {
  RuntimeGuard,
} from "../types/playground";

import type {
  CollectionConfig,
} from "../types/collection";

import type {
  ParsingMode,
  ParsingResult,
} from "./safe-parsing";

import type {
  ValidationResult,
} from "../types/playground";

type CollectionEvaluation = {
  validation: ValidationResult;
  parsing: ParsingResult;
};

function getGuard(config: CollectionConfig): RuntimeGuard {
  const element = guardLookup[config.elementGuard].guard;
  const key = guardLookup[config.keyGuard].guard;

  // The playground uses the common RuntimeGuard
  // interface to evaluate guards of different types.
  switch (config.kind) {
    case "arrayOf":
      return arrayOf(element);

    case "nonEmptyArrayOf":
      return nonEmptyArrayOf(element);

    case "tupleOf": {
      if (config.tupleGuards.length === 0) {
        throw new Error("Add at least one tuple position.");
      }

      const guards = config.tupleGuards.map(
        (name) => guardLookup[name].guard
      );

      return tupleOf(...guards);
    }

    case "setOf":
      return setOf(element);

    case "mapOf":
      return mapOf(key, element);

    case "recordOf":
    return recordOf(
        (value: unknown): value is string =>
        typeof value === "string" && key(value),
        element
    );
  }
}

function convertCollectionInput(
  value: unknown,
  config: CollectionConfig
): unknown {
  if (config.kind === "setOf") {
    if (!Array.isArray(value)) {
      throw new Error(
        "Set input must be a JSON array. The playground converts it into a JavaScript Set."
      );
    }

    return new Set(value);
  }

  if (config.kind === "mapOf") {
    if (
      !Array.isArray(value) ||
      !value.every(
        (entry) =>
          Array.isArray(entry) &&
          entry.length === 2
      )
    ) {
      throw new Error(
        'Map input must be an array of [key, value] pairs, for example [["age", 28]].'
      );
    }

    return new Map(
      value as [unknown, unknown][]
    );
  }

  return value;
}

function describeValue(value: unknown): string {
  if (value instanceof Map) {
    return `Map with ${value.size} entries`;
  }

  if (value instanceof Set) {
    return `Set with ${value.size} unique values`;
  }

  if (Array.isArray(value)) {
    return `Array with ${value.length} elements`;
  }

  if (value !== null && typeof value === "object") {
    return "Object";
  }

  return typeof value;
}

export function evaluateCollection(
  input: string,
  config: CollectionConfig,
  mode: ParsingMode
): CollectionEvaluation {
  try {
    const guard = getGuard(config);

    let parsed: unknown;

    try {
      parsed = JSON.parse(input);
    } catch {
      return {
        validation: {
          status: "invalid",
          explanation: "Enter valid JSON to test this collection.",
          details: ["The input could not be parsed as JSON."],
        },
        parsing: {
          mode,
          valid: null,
          error: "Invalid JSON input.",
        },
      };
    }

    const value = convertCollectionInput(parsed, config);
    const passed = guard(value);

    const validation: ValidationResult = {
      status: passed ? "pass" : "fail",
      value:
        value instanceof Map
          ? Array.from(value.entries())
          : value instanceof Set
            ? Array.from(value.values())
            : value,
      explanation: passed
        ? `${config.kind} accepted the supplied ${describeValue(value)}.`
        : `${config.kind} rejected the supplied ${describeValue(value)}.`,
      details: [
        `Guard: ${config.kind}`,
        `Element/value guard: ${config.elementGuard}`,
        ...(config.kind === "mapOf" ||
        config.kind === "recordOf"
          ? [`Key guard: ${config.keyGuard}`]
          : []),
        ...(config.kind === "tupleOf"
          ? [
              `Tuple positions: ${config.tupleGuards.join(", ")}`,
            ]
          : []),
        ...(config.kind === "setOf" ||
        config.kind === "mapOf"
          ? [
              "The playground converted JSON input into a JavaScript collection before validation.",
            ]
          : []),
        "is-kit provides the guard result. This explanation is generated by the playground.",
      ],
    };

    if (mode === "safeParse") {
      const result = safeParse(guard, value);

      return {
        validation,
        parsing: result.valid
          ? {
              mode,
              valid: true,
              value: validation.value,
            }
          : {
              mode,
              valid: false,
            },
      };
    }

    if (mode === "safeJsonParse") {
      // safeJsonParse parses JSON itself. It cannot
      // directly construct Set or Map instances.
      if (
        config.kind === "setOf" ||
        config.kind === "mapOf"
      ) {
        return {
          validation,
          parsing: {
            mode,
            valid: null,
            error:
              "safeJsonParse cannot create a Set or Map from JSON. Use Direct Guard or safeParse for these collections.",
          },
        };
      }

      const result = safeJsonParse(input, guard);

      return {
        validation,
        parsing: result.valid
          ? {
              mode,
              valid: true,
              value: result.value,
            }
          : {
              mode,
              valid: false,
            },
      };
    }

    return {
      validation,
      parsing: {
        mode,
        valid: passed,
        value: validation.value,
      },
    };
  } catch (error) {
    const message =
      error instanceof Error
        ? error.message
        : "Unable to evaluate the collection.";

    return {
      validation: {
        status: "invalid",
        explanation: message,
        details: [],
      },
      parsing: {
        mode,
        valid: null,
        error: message,
      },
    };
  }
}
